export interface ProjectPageSpec {
  slug: 'p1' | 'p2' | 'p3' | 'p4';
  title: string;
  layout: LayoutId;
}

export interface ProjectArtPlan {
  theme: string;
  font: string;
  persona: string;
  pages: [ProjectPageSpec, ProjectPageSpec, ProjectPageSpec, ProjectPageSpec];
}

function plan(
  theme: string,
  font: string,
  persona: string,
  p1: [string, LayoutId],
  p2: [string, LayoutId],
  p3: [string, LayoutId],
  p4: [string, LayoutId]
): ProjectArtPlan {
  return {
    theme,
    font,
    persona,
    pages: [
      { slug: 'p1', title: p1[0], layout: p1[1] },
      { slug: 'p2', title: p2[0], layout: p2[1] },
      { slug: 'p3', title: p3[0], layout: p3[1] },
      { slug: 'p4', title: p4[0], layout: p4[1] },
    ],
  };
}

export function getPageScreenshotPath(projectId: string, slug: 'p1' | 'p2' | 'p3' | 'p4'): string {
  return slug === 'p1' ? `./screenshots/${projectId}.webp` : `./screenshots/${projectId}-${slug}.webp`;
}

