export type ProjectPageSlug =
  | 'p1' | 'p2' | 'p3' | 'p4' | 'p5' | 'p6'
  | 'p7' | 'p8' | 'p9' | 'p10' | 'p11' | 'p12';

export interface ProjectPageSpec {
  slug: ProjectPageSlug;
  title: string;
  layout: LayoutId | 'enterprise-bespoke';
}

export interface ProjectArtPlan {
  theme: string;
  font: string;
  persona: string;
  enterpriseVerified?: boolean;
  designReference?: string;
  resolution?: string;
  pages: ProjectPageSpec[];
}

function plan(
  theme: string,
  font: string,
  persona: string,
  p1: [string, LayoutId],
  p2: [string, LayoutId],
  p3: [string, LayoutId],
  p4: [string, LayoutId]
): ProjectArtPlan {
  return {
    theme,
    font,
    persona,
    pages: [
      { slug: 'p1', title: p1[0], layout: p1[1] },
      { slug: 'p2', title: p2[0], layout: p2[1] },
      { slug: 'p3', title: p3[0], layout: p3[1] },
      { slug: 'p4', title: p4[0], layout: p4[1] },
    ],
  };
}

function enterprisePlan(
  designReference: string,
  persona: string,
  titles: string[]
): ProjectArtPlan {
  const slugs: ProjectPageSlug[] = [
    'p1', 'p2', 'p3', 'p4', 'p5', 'p6',
    'p7', 'p8', 'p9', 'p10', 'p11', 'p12',
  ];
  return {
    theme: 'enterprise-bespoke',
    font: 'enterprise-bespoke',
    persona,
    enterpriseVerified: true,
    designReference,
    resolution: '1600×1000 @ 2x',
    pages: titles.map((title, idx) => ({
      slug: slugs[idx],
      title,
      layout: 'enterprise-bespoke',
    })),
  };
}

export function getPageScreenshotUrl(projectId: string, slug: ProjectPageSlug): string {
  const base = (import.meta.env?.BASE_URL ?? '/').replace(/\/?$/, '/');
  return slug === 'p1' ? `${base}screenshots/${projectId}.webp` : `${base}screenshots/${projectId}-${slug}.webp`;
}

